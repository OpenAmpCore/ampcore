import java.io.File
import org.apache.tools.ant.taskdefs.condition.Os
import org.gradle.api.DefaultTask
import org.gradle.api.GradleException
import org.gradle.api.logging.LogLevel
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.TaskAction

open class BuildTask : DefaultTask() {
    @Input
    var rootDirRel: String? = null
    @Input
    var target: String? = null
    @Input
    var release: Boolean? = null

    @TaskAction
    fun assemble() {
        val executable = """node""";
        try {
            runTauriCli(executable)
        } catch (e: Exception) {
            if (Os.isFamily(Os.FAMILY_WINDOWS)) {
                // Try different Windows-specific extensions
                val fallbacks = listOf(
                    "$executable.exe",
                    "$executable.cmd",
                    "$executable.bat",
                )
                
                var lastException: Exception = e
                for (fallback in fallbacks) {
                    try {
                        runTauriCli(fallback)
                        return
                    } catch (fallbackException: Exception) {
                        lastException = fallbackException
                    }
                }
                throw lastException
            } else {
                throw e;
            }
        }
    }

    fun runTauriCli(executable: String) {
        val rootDirRel = rootDirRel ?: throw GradleException("rootDirRel cannot be null")
        val target = target ?: throw GradleException("target cannot be null")
        val release = release ?: throw GradleException("release cannot be null")
        // WORKAROUND for a known upstream Tauri CLI bug on Windows (not yet
        // released as of tauri-cli 2.11.4): `node tauri ...` tries to resolve
        // a bare module literally named "tauri" via Node's module-resolution
        // walk, which fails even when @tauri-apps/cli is installed and
        // working from the CLI directly.
        // https://github.com/tauri-apps/tauri/issues/13892 (fix landed as
        // PR #14146, using `cargo tauri` instead of `node tauri` — not
        // available here since tauri-cli isn't installed as a cargo binary).
        // Point Node straight at the installed CLI's JS entry point instead,
        // relative to this task's workingDir (rootDirRel, "apps/mobile/src-tauri")
        // — apps/mobile/package.json declares @tauri-apps/cli itself, so the
        // CLI lives in apps/mobile's own node_modules, one level up from here.
        // NOTE: this file is regenerated by `tauri android init`; if that's
        // ever re-run, re-apply this edit (or drop it once the upstream fix ships).
        val args = listOf("../node_modules/@tauri-apps/cli/tauri.js", "android", "android-studio-script");

        project.exec {
            workingDir(File(project.projectDir, rootDirRel))
            executable(executable)
            args(args)
            if (project.logger.isEnabled(LogLevel.DEBUG)) {
                args("-vv")
            } else if (project.logger.isEnabled(LogLevel.INFO)) {
                args("-v")
            }
            if (release) {
                args("--release")
            }
            args(listOf("--target", target))
        }.assertNormalExitValue()
    }
}